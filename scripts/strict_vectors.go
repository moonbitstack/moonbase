// Writes src/base64/strict_vectors_test.mbt and src/base32/strict_vectors_test.mbt:
// what Go's encoding/base64 and encoding/base32 make of each input under each
// combination of padding and strictness that has a Go counterpart.
//
//	go run scripts/strict_vectors.go
package main

import (
	"encoding/base32"
	"encoding/base64"
	"fmt"
	"os"
	"strings"
)

type decoder interface {
	DecodeString(string) ([]byte, error)
}

type mode struct {
	padding, strict bool
	dec             decoder
}

func table(pkg string, inputs []string, modes []mode) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by scripts/strict_vectors.go from Go's encoding/%s. Do not edit.\n\n", pkg)
	b.WriteString("///|\nlet strict_vectors : Array[(String, Bool, Bool, Bytes?)] = [\n")
	for _, m := range modes {
		for _, in := range inputs {
			out, err := m.dec.DecodeString(in)
			want := "None"
			if err == nil {
				var hex strings.Builder
				for _, c := range out {
					fmt.Fprintf(&hex, "\\x%02x", c)
				}
				want = "Some(b\"" + hex.String() + "\")"
			}
			fmt.Fprintf(&b, "  (%q, %v, %v, %s),\n", in, m.padding, m.strict, want)
		}
	}
	b.WriteString("]\n")
	return b.String()
}

func write(path, text string) {
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		panic(err)
	}
}

func main() {
	b64 := []string{
		"", "Zg", "Zg==", "Zh", "Zh==", "Zg=", "Zg===", "Zm8", "Zm8=", "Zm9", "Zm9=",
		"Zm9v", "Zm9v=", "Zm9vYg", "Zm9vYh", "Zm9vYg==", "Zm9vYh==", "Zm9vYmE",
		"Zm9vYmF", "Zm9vYmE=", "Zm9vYmF=", "Zm9vYmFy", "Z", "Z===", "Zg=a", "QQ",
		"QR==", "/w", "/x==", "//8", "//+=", "////",
	}
	write("src/base64/strict_vectors_test.mbt", table("base64", b64, []mode{
		{true, false, base64.StdEncoding},
		{true, true, base64.StdEncoding.Strict()},
		{false, false, base64.RawStdEncoding},
		{false, true, base64.RawStdEncoding.Strict()},
	}))

	// encoding/base32 has no strict mode, so only padding is compared here. It
	// also reads two inputs RFC 4648 rules out, a full group and one more "="
	// ("MY=======") and, unpadded, a lone character ("M"); both are tested by
	// hand instead.
	b32 := []string{
		"", "MY", "MY======", "MY=====", "MZXQ", "MZXQ====", "MZXW6",
		"MZXW6===", "MZXW6YQ", "MZXW6YQ=", "MZXW6YTB", "MZXW6YTBOI", "MZXW6YTBOI======",
		"M=======",
	}
	write("src/base32/strict_vectors_test.mbt", table("base32", b32, []mode{
		{true, false, base32.StdEncoding},
		{false, false, base32.StdEncoding.WithPadding(base32.NoPadding)},
	}))
}
